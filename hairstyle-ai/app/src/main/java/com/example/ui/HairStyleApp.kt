import com.example.ui.screens.detail.BarberGuideScreen
import com.example.ui.screens.detail.HairstyleDetailScreen
import com.example.ui.screens.favorites.FavoritesScreen
import com.example.ui.screens.gallery.ChooseStyleScreen
import com.example.ui.screens.gallery.MenGalleryScreen
import com.example.ui.screens.gallery.SearchExploreScreen
import com.example.ui.screens.gallery.WomenGalleryScreen
import com.example.ui.screens.home.HomeScreen
import com.example.ui.screens.outfit.ClothesHomeScreen
import com.example.ui.screens.outfit.ClothesTryOnScreen
import com.example.ui.screens.profile.ProfileScreen
import com.example.ui.screens.splash.SplashScreen
import com.example.ui.screens.tryon.CompareStylesScreen
import com.example.ui.screens.tryon.FaceShapeScreen
import com.example.ui.screens.tryon.PaidAiStudioScreen
import com.example.ui.screens.tryon.PhotoPreviewScreen
import com.example.ui.screens.tryon.TryHairstyleScreen
import com.example.ui.screens.tryon.TryOnMode
import com.example.ui.screens.tryon.TryOnProcessingScreen
import com.example.ui.screens.tryon.TryOnResultScreen
import com.example.ui.screens.welcome.StyleWelcomeScreen
import com.example.ui.viewmodel.HairstyleViewModel

@Composable
fun HairStyleApp(
    viewModel: HairstyleViewModel = viewModel()
) {
    // Start directly on Home screen (Main Hairstyle discovery, catalog, and try-on studio)
    val navStack = remember { mutableStateListOf<AppScreen>(AppScreen.Home) }
    val currentScreen = navStack.lastOrNull() ?: AppScreen.Home

    val favoriteIds by viewModel.favoriteIds.collectAsState()
    val homeGender by viewModel.homeGender.collectAsState()
    val homeMenCategory by viewModel.homeMenCategory.collectAsState()
    val homeWomenCategory by viewModel.homeWomenCategory.collectAsState()
    val homeSearchQuery by viewModel.homeSearchQuery.collectAsState()
    val isHomeSearchVisible by viewModel.isHomeSearchVisible.collectAsState()
    val menCategory by viewModel.menCategory.collectAsState()
    val menSearch by viewModel.menSearch.collectAsState()
    val womenCategory by viewModel.womenCategory.collectAsState()
    val womenSearch by viewModel.womenSearch.collectAsState()
    val activeTryOnItem by viewModel.activeTryOnItem.collectAsState()
    val userPhoto by viewModel.userPhoto.collectAsState()
    val aiResultBitmap by viewModel.aiResultBitmap.collectAsState()
    val isAiGenerated by viewModel.isAiGenerated.collectAsState()
    val aiErrorMessage by viewModel.aiErrorMessage.collectAsState()
    val isProcessing by viewModel.isProcessing.collectAsState()
    val processingStage by viewModel.processingStage.collectAsState()
    val remainingFreeQuota by viewModel.remainingFreeQuota.collectAsState()
    val selectedColorTint by viewModel.selectedColorTint.collectAsState()
    val userProfile by viewModel.userProfile.collectAsState()
    val tryOnHistory by viewModel.tryOnHistory.collectAsState()
    val isDarkTheme by viewModel.isDarkTheme.collectAsState()
    val isPaidVersion by viewModel.isPaidVersion.collectAsState()
    val isPaidSubscribed by viewModel.isPaidSubscribed.collectAsState()
    val selectedLanguage by viewModel.selectedLanguage.collectAsState()
    val feedbackMessage by viewModel.userFeedback.collectAsState()

    var quickChoiceItem by remember { mutableStateOf<HairstyleItem?>(null) }
    var showQuickSubscriptionDialog by remember { mutableStateOf(false) }

    val snackbarHostState = remember { SnackbarHostState() }

    LaunchedEffect(feedbackMessage) {
        feedbackMessage?.let {
            snackbarHostState.showSnackbar(it)
            viewModel.clearFeedback()
        }
    }

    fun navigateTo(screen: AppScreen) {
        if (screen == AppScreen.Welcome || screen == AppScreen.ClothesHome) {
            navStack.clear()
            navStack.add(screen)
        } else if (screen == AppScreen.Home || screen == AppScreen.MenGallery ||
            screen == AppScreen.WomenGallery || screen == AppScreen.Favorites ||
            screen == AppScreen.Profile || screen == AppScreen.PaidAiStudio
        ) {
            // Root tab navigation: clear stack and replace
            navStack.clear()
            navStack.add(screen)
        } else {
            navStack.add(screen)
        }
    }

    fun popBack() {
        if (navStack.size > 1) {
            navStack.removeAt(navStack.lastIndex)
        }
    }

    // Quick Try-On Choice Bottom Sheet (triggered from card quick-try buttons)
    if (quickChoiceItem != null) {
        TryOnChoiceBottomSheet(
            hairstyle = quickChoiceItem,
            isPaidSubscribed = isPaidSubscribed,
            onDismissRequest = { quickChoiceItem = null },
            onSelectLiveCamera = {
                val item = quickChoiceItem!!
                quickChoiceItem = null
                viewModel.setActiveTryOnItem(item)
                navigateTo(AppScreen.TryHairstyle(item.id))
            },
            onSelectUploadPhoto = {
                val item = quickChoiceItem!!
                quickChoiceItem = null
                viewModel.setActiveTryOnItem(item)
                navigateTo(AppScreen.CameraUpload(item.id))
            }
        )
    }

    // $2.00 Subscription Dialog for quick try
    if (showQuickSubscriptionDialog) {
        PaidSubscriptionDialog(
            onDismissRequest = { showQuickSubscriptionDialog = false },
            onConfirmPayTwoDollars = {
                viewModel.subscribePaidVersion {
                    showQuickSubscriptionDialog = false
                    navigateTo(AppScreen.PaidAiStudio)
                }
            }
        )
    }

    // Handle system back navigation
    BackHandler(enabled = navStack.size > 1) {
        popBack()
    }

    val isRootTab = currentScreen is AppScreen.Home ||
            currentScreen is AppScreen.MenGallery ||
            currentScreen is AppScreen.WomenGallery ||
            currentScreen is AppScreen.Favorites ||
            currentScreen is AppScreen.Profile ||
            currentScreen is AppScreen.PaidAiStudio

    Scaffold(
        modifier = Modifier.fillMaxSize(),
        snackbarHost = { SnackbarHost(snackbarHostState) },
        bottomBar = {
            if (isRootTab && currentScreen !is AppScreen.Splash) {
                AppBottomNavBar(
                    currentScreen = currentScreen,
                    onNavigate = { navigateTo(it) },
                    favoritesCount = favoriteIds.size,
                    isPaidVersion = isPaidVersion
                )
            }
        }
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
        ) {
            AnimatedContent(
                targetState = currentScreen,
                transitionSpec = { fadeIn() togetherWith fadeOut() },
                label = "screen_transition"
            ) { screen ->
                when (screen) {
                    is AppScreen.Welcome -> {
                        StyleWelcomeScreen(
                            onSelectHairstyles = {
                                navigateTo(AppScreen.Home)
                            },
                            onSelectClothes = {
                                navigateTo(AppScreen.ClothesHome)
                            }
                        )
                    }

                    is AppScreen.ClothesHome -> {
                        ClothesHomeScreen(
                            onNavigateBack = {
                                navStack.clear()
                                navStack.add(AppScreen.Welcome)
                            },
                            onTryOutfit = { outfit ->
                                navigateTo(AppScreen.ClothesTryOn(outfit.id))
                            },
                            isDarkTheme = isDarkTheme,
                            onThemeChanged = { viewModel.setDarkTheme(it) }
                        )
                    }

                    is AppScreen.ClothesTryOn -> {
                        ClothesTryOnScreen(
                            initialOutfitId = screen.outfitId,
                            onNavigateBack = { popBack() }
                        )
                    }

                    is AppScreen.Splash -> {
                        SplashScreen(
                            onGetStarted = {
                                navigateTo(AppScreen.Home)
                            },
                            onLogin = {
                                navigateTo(AppScreen.Home)
                            }
                        )
                    }

                    is AppScreen.Home -> {
                        HomeScreen(
                            selectedGender = homeGender,
                            onGenderSelected = { viewModel.setHomeGender(it) },
                            selectedCategory = if (homeGender == Gender.MEN) homeMenCategory else homeWomenCategory,
                            onCategorySelected = {
                                if (homeGender == Gender.MEN) {
                                    viewModel.setHomeMenCategory(it)
                                } else {
                                    viewModel.setHomeWomenCategory(it)
                                }
                            },
                            searchQuery = homeSearchQuery,
                            onSearchQueryChanged = { viewModel.setHomeSearchQuery(it) },
                            isSearchOpen = isHomeSearchVisible,
                            onToggleSearch = { viewModel.toggleHomeSearch() },
                            onNavigateToProfile = { navigateTo(AppScreen.Profile) },
                            onSelectHairstyle = { id -> navigateTo(AppScreen.Detail(id)) },
                            onQuickTryOn = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onToggleFavorite = { viewModel.toggleFavorite(it) },
                            isFavorite = { viewModel.isFavorite(it) },
                            onNavigateToMen = { navigateTo(AppScreen.MenGallery) },
                            onNavigateToWomen = { navigateTo(AppScreen.WomenGallery) },
                            onNavigateToLiveAr = { navigateTo(AppScreen.TryHairstyle()) },
                            onNavigateToFaceShape = { navigateTo(AppScreen.FaceShape) },
                            onNavigateToCompare = { navigateTo(AppScreen.CompareStyles()) },
                            onNavigateToBarberGuide = { navigateTo(AppScreen.BarberGuide()) },
                            currentLanguage = selectedLanguage,
                            onLanguageSelected = { viewModel.setLanguage(it) },
                            isPaidSubscribed = isPaidSubscribed,
                            onUpgradeClick = { showQuickSubscriptionDialog = true },
                            onNavigateToPhotoUpload = { navigateTo(AppScreen.CameraUpload()) },
                            onNavigateToFavorites = { navigateTo(AppScreen.Favorites) },
                            onNavigateBack = null,
                            userName = userProfile.userName
                        )
                    }

                    is AppScreen.ChooseStyle -> {
                        ChooseStyleScreen(
                            onSelectMen = {
                                viewModel.setHomeGender(Gender.MEN)
                                navigateTo(AppScreen.MenGallery)
                            },
                            onSelectWomen = {
                                viewModel.setHomeGender(Gender.WOMEN)
                                navigateTo(AppScreen.WomenGallery)
                            },
                            onBack = if (navStack.size > 1) { { popBack() } } else null
                        )
                    }

                    is AppScreen.CompareStyles -> {
                        CompareStylesScreen(
                            initialStyleId1 = screen.styleId1,
                            initialStyleId2 = screen.styleId2,
                            onTryStyle = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onSelectHairstyle = { id ->
                                navigateTo(AppScreen.Detail(id))
                            },
                            onBack = { popBack() }
                        )
                    }

                    is AppScreen.FaceShape -> {
                        FaceShapeScreen(
                            onSelectHairstyle = { id -> navigateTo(AppScreen.Detail(id)) },
                            onTryLive = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onBack = { popBack() },
                            onFaceShapeDetected = { viewModel.updateUserFaceShape(it) },
                            initialFaceShape = userProfile.faceShape
                        )
                    }

                    is AppScreen.BarberGuide -> {
                        BarberGuideScreen(
                            hairstyleId = screen.hairstyleId,
                            onTryLive = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onBack = { popBack() }
                        )
                    }

                    is AppScreen.SearchExplore -> {
                        SearchExploreScreen(
                            onSelectHairstyle = { id -> navigateTo(AppScreen.Detail(id)) },
                            onQuickTryOn = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onToggleFavorite = { viewModel.toggleFavorite(it) },
                            isFavorite = { viewModel.isFavorite(it) },
                            onBack = if (navStack.size > 1) { { popBack() } } else null
                        )
                    }

                    is AppScreen.MenGallery -> {
                        MenGalleryScreen(
                            selectedCategory = menCategory,
                            searchQuery = menSearch,
                            onCategorySelected = { viewModel.setMenCategory(it) },
                            onSearchQueryChanged = { viewModel.setMenSearch(it) },
                            onSelectHairstyle = { id -> navigateTo(AppScreen.Detail(id)) },
                            onQuickTryOn = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onToggleFavorite = { viewModel.toggleFavorite(it) },
                            isFavorite = { viewModel.isFavorite(it) },
                            onBack = if (navStack.size > 1) { { popBack() } } else null
                        )
                    }

                    is AppScreen.WomenGallery -> {
                        WomenGalleryScreen(
                            selectedCategory = womenCategory,
                            searchQuery = womenSearch,
                            onCategorySelected = { viewModel.setWomenCategory(it) },
                            onSearchQueryChanged = { viewModel.setWomenSearch(it) },
                            onSelectHairstyle = { id -> navigateTo(AppScreen.Detail(id)) },
                            onQuickTryOn = { item ->
                                viewModel.setActiveTryOnItem(item)
                                navigateTo(AppScreen.TryHairstyle(item.id))
                            },
                            onToggleFavorite = { viewModel.toggleFavorite(it) },
                            isFavorite = { viewModel.isFavorite(it) },
                            onBack = if (navStack.size > 1) { { popBack() } } else null
                        )
                    }

                    is AppScreen.Detail -> {
                        val item = HairstyleRepository.getById(screen.hairstyleId)
                            ?: HairstyleRepository.getAllHairstyles().first()
                        HairstyleDetailScreen(
                            item = item,
                            isFavorite = viewModel.isFavorite(item.id),
                            isPaidSubscribed = isPaidSubscribed,
                            onBack = { popBack() },
                            onToggleFavorite = { viewModel.toggleFavorite(item.id) },
                            onTryThisStyle = { selectedItem ->
                                viewModel.setActiveTryOnItem(selectedItem)
                                navigateTo(AppScreen.TryHairstyle(selectedItem.id))
                            },
                            onShowToBarber = { hairstyleId ->
                                navigateTo(AppScreen.BarberGuide(hairstyleId))
                            }
                        )
                    }

                    is AppScreen.TryHairstyle, is AppScreen.CameraUpload -> {
                        val styleId = if (screen is AppScreen.TryHairstyle) screen.hairstyleId else (screen as AppScreen.CameraUpload).hairstyleId
                        val item = styleId?.let { HairstyleRepository.getById(it) } ?: activeTryOnItem
                        val initialMode = if (screen is AppScreen.CameraUpload) TryOnMode.UPLOAD_PHOTO else TryOnMode.LIVE_CAMERA
                        TryHairstyleScreen(
                            hairstyle = item,
                            initialMode = initialMode,
                            onBack = { popBack() },
                            onPhotoSelected = { photoSource ->
                                viewModel.setUserPhoto(photoSource)
                                navigateTo(AppScreen.PhotoPreview(item?.id))
                            },
                            onChangeHairstyle = {
                                if (item?.gender == Gender.WOMEN) {
                                    navigateTo(AppScreen.WomenGallery)
                                } else {
                                    navigateTo(AppScreen.MenGallery)
                                }
                            },
                            onShowToBarber = { id ->
                                navigateTo(AppScreen.BarberGuide(id))
                            }
                        )
                    }

                    is AppScreen.PhotoPreview -> {
                        val item = screen.hairstyleId?.let { HairstyleRepository.getById(it) } ?: activeTryOnItem
                        PhotoPreviewScreen(
                            userPhoto = userPhoto,
                            hairstyle = item,
                            onChangeHairstyle = {
                                if (item?.gender == Gender.WOMEN) {
                                    navigateTo(AppScreen.WomenGallery)
                                } else {
                                    navigateTo(AppScreen.MenGallery)
                                }
                            },
                            onRetakePhoto = {
                                viewModel.clearUserPhoto()
                                popBack()
                            },
                            onBack = { popBack() },
                            onShowToBarber = { id ->
                                navigateTo(AppScreen.BarberGuide(id))
                            }
                        )
                    }

                    is AppScreen.Processing -> {
                        val item = screen.hairstyleId?.let { HairstyleRepository.getById(it) } ?: activeTryOnItem
                        TryOnProcessingScreen(
                            hairstyle = item,
                            currentStage = processingStage,
                            onCancel = {
                                viewModel.cancelTryOn()
                                popBack()
                            }
                        )
                    }

                    is AppScreen.TryOnResult -> {
                        val item = screen.hairstyleId?.let { HairstyleRepository.getById(it) } ?: activeTryOnItem
                        TryOnResultScreen(
                            hairstyle = item,
                            userPhoto = userPhoto,
                            aiResultBitmap = aiResultBitmap,
                            remainingFreeQuota = remainingFreeQuota,
                            maxDailyQuota = viewModel.maxDailyQuota,
                            selectedColorTint = selectedColorTint,
                            onColorTintSelected = { viewModel.setSelectedColorTint(it) },
                            onSaveResult = {
                                viewModel.showFeedback("Makeover look saved to photo gallery!")
                            },
                            onDeleteResult = {
                                viewModel.deleteCurrentAiResult()
                            },
                            onTryAnotherStyle = {
                                navStack.clear()
                                navStack.add(AppScreen.Home)
                            },
                            onChangeHairstyle = {
                                if (item?.gender == Gender.WOMEN) {
                                    navigateTo(AppScreen.WomenGallery)
                                } else {
                                    navigateTo(AppScreen.MenGallery)
                                }
                            },
                            onTryAgain = {
                                navigateTo(AppScreen.PhotoPreview(item?.id))
                            },
                            onBack = { popBack() }
                        )
                    }

                    is AppScreen.Favorites -> {
                        FavoritesScreen(
                            favoriteIds = favoriteIds,
                            onToggleFavorite = { viewModel.toggleFavorite(it) },
                            onSelectHairstyle = { id -> navigateTo(AppScreen.Detail(id)) },
                            onQuickTryOn = { item -> quickChoiceItem = item },
                            onExploreStyles = {
                                navigateTo(AppScreen.Home)
                            }
                        )
                    }

                    is AppScreen.Profile -> {
                        ProfileScreen(
                            savedCount = favoriteIds.size,
                            userProfile = userProfile,
                            tryOnHistory = tryOnHistory,
                            isDarkTheme = isDarkTheme,
                            onThemeChanged = { viewModel.setDarkTheme(it) },
                            onNavigateToFavorites = { navigateTo(AppScreen.Favorites) },
                            onFaceShapeChanged = { viewModel.updateUserFaceShape(it) },
                            onHairTypeChanged = { viewModel.updateUserHairType(it) },
                            onUpdateUserName = { viewModel.updateUserName(it) },
                            onClearHistory = { viewModel.clearAllHistory() },
                            onClearFavorites = { viewModel.clearAllFavorites() }
                        )
                    }

                    is AppScreen.PaidAiStudio -> {
                        PaidAiStudioScreen(
                            userPhoto = userPhoto,
                            onUserPhotoChanged = { viewModel.setUserPhoto(it) },
                            onBack = {
                                if (navStack.size > 1) popBack() else navigateTo(AppScreen.Home)
                            },
                            onOpenLiveCamera = { navigateTo(AppScreen.TryHairstyle()) }
                        )
                    }
                }
            }
        }
    }
}
