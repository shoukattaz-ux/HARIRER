import com.google.gms.googleservices.GoogleServicesPlugin.MissingGoogleServicesStrategy

// Release builds must not ship the Gemini API key: AI calls go through Firebase AI Logic + App Check.
// Set hairlook.allowClientGeminiKeyInRelease=true in gradle.properties only as a temporary escape hatch.
val allowClientGeminiKeyInRelease =
  (findProperty("hairlook.allowClientGeminiKeyInRelease") as String?)?.toBoolean() ?: false

plugins {
  alias(libs.plugins.android.application)
  alias(libs.plugins.kotlin.compose)
  alias(libs.plugins.google.devtools.ksp)
  alias(libs.plugins.secrets)
  alias(libs.plugins.google.services)
}

android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.hairstyleai.vqzpmk"
    minSdk = 24
    targetSdk = 36
    // CI sets VERSION_CODE / VERSION_NAME so every build is newer than the last (needed by the updater)
    versionCode = providers.environmentVariable("VERSION_CODE").orNull?.toIntOrNull() ?: 3
    versionName = providers.environmentVariable("VERSION_NAME").orNull ?: "1.2"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  signingConfigs {
    create("release") {
      val keystorePath = System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks"
      storeFile = file(keystorePath)
      storePassword = System.getenv("STORE_PASSWORD")
      keyAlias = "upload"
      keyPassword = System.getenv("KEY_PASSWORD")
    }
    create("debugConfig") {
      storeFile = file("${rootDir}/debug.keystore")
      storePassword = "android"
      keyAlias = "androiddebugkey"
      keyPassword = "android"
    }
  }

  buildTypes {
    release {
      buildConfigField("boolean", "ALLOW_CLIENT_GEMINI_KEY", allowClientGeminiKeyInRelease.toString())
      isCrunchPngs = false
      isMinifyEnabled = false
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release")
    }
    debug {
      buildConfigField("boolean", "ALLOW_CLIENT_GEMINI_KEY", "true")
      // debug.keystore is git-ignored: use it when present, otherwise Android's default debug key
      if (file("${rootDir}/debug.keystore").exists()) {
        signingConfig = signingConfigs.getByName("debugConfig")
      }
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_11
    targetCompatibility = JavaVersion.VERSION_11
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

// Configure the Secrets Gradle Plugin to use .env and .env.example files
// to match the convention used in Web projects.
secrets {
  propertiesFileName = ".env"
  defaultPropertiesFileName = ".env.example"
  ignoreList.add("FIREBASE_APPCHECK_DEBUG_TOKEN")
}

googleServices { missingGoogleServicesStrategy = MissingGoogleServicesStrategy.WARN }

// Overrides the key injected by the Secrets plugin so release APKs/AABs never contain it.
androidComponents {
  onVariants(selector().withBuildType("release")) { variant ->
    if (!allowClientGeminiKeyInRelease) {
      variant.buildConfigFields?.put(
        "GEMINI_API_KEY",
        com.android.build.api.variant.BuildConfigField(
          "String",
          "\"\"",
          "Stripped from release builds; use Firebase AI Logic"
        )
      )
    }
  }
}

